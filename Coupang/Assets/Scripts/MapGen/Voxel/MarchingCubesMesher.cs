    /// <summary>
    /// Builds a smoothed scalar field (density) and a corner material map
    /// from the discrete voxel grid.
    /// 
    /// density[cx,cy,cz] in [0,1]:
    ///   - 0: fully air
    ///   - 1: fully solid
    /// Values in between from averaging neighbor voxels -> smoother iso-surface.
    /// 
    /// cornerMat[cx,cy,cz] = dominant VoxelType around that corner (for materials).
    /// </summary>
    private static void BuildScalarField(
        VoxelType[,,] voxels,
        float[,,] density,
        VoxelType[,,] cornerMat)
    {
        int sizeX = voxels.GetLength(0);
        int sizeY = voxels.GetLength(1);
        int sizeZ = voxels.GetLength(2);

        int gx = sizeX + 1;
        int gy = sizeY + 1;
        int gz = sizeZ + 1;

        for (int cx = 0; cx < gx; cx++)
        {
            for (int cy = 0; cy < gy; cy++)
            {
                for (int cz = 0; cz < gz; cz++)
                {
                    int solidCount = 0;
                    int totalCount = 0;

                    int groundCount = 0;
                    int undergroundCount = 0;
                    int caveCount = 0;

                    // Look at up to 8 neighbor voxels that share this corner.
                    for (int vx = cx - 1; vx <= cx; vx++)
                    {
                        if (vx < 0 || vx >= sizeX) continue;
                        for (int vy = cy - 1; vy <= cy; vy++)
                        {
                            if (vy < 0 || vy >= sizeY) continue;
                            for (int vz = cz - 1; vz <= cz; vz++)
                            {
                                if (vz < 0 || vz >= sizeZ) continue;

                                totalCount++;
                                VoxelType vt = voxels[vx, vy, vz];

                                if (vt != VoxelType.Air)
                                {
                                    solidCount++;
                                    switch (vt)
                                    {
                                        case VoxelType.Ground: groundCount++; break;
                                        case VoxelType.Underground: undergroundCount++; break;
                                        case VoxelType.Cave: caveCount++; break;
                                    }
                                }
                            }
                        }
                    }

                    float d = 0f;
                    if (totalCount > 0)
                    {
                        d = (float)solidCount / totalCount;
                    }
                    density[cx, cy, cz] = d;

                    // pick dominant material
                    if (solidCount == 0)
                    {
                        cornerMat[cx, cy, cz] = VoxelType.Air;
                    }
                    else
                    {
                        if (groundCount >= undergroundCount && groundCount >= caveCount)
                            cornerMat[cx, cy, cz] = VoxelType.Ground;
                        else if (undergroundCount >= groundCount && undergroundCount >= caveCount)
                            cornerMat[cx, cy, cz] = VoxelType.Underground;
                        else
                            cornerMat[cx, cy, cz] = VoxelType.Cave;
                    }
                }
            }
        }
    }

    /// <summary>
    /// Returns the dominant material type among the 8 cube corners.
    /// </summary>
    private static VoxelType PickDominantMaterial(VoxelType[] cornerTypes)
    {
        int ground = 0;
        int underground = 0;
        int cave = 0;

        for (int i = 0; i < 8; i++)
        {
            switch (cornerTypes[i])
            {
                case VoxelType.Ground: ground++; break;
                case VoxelType.Underground: underground++; break;
                case VoxelType.Cave: cave++; break;
            }
        }

        if (ground >= underground && ground >= cave && ground > 0)
            return VoxelType.Ground;
        if (underground >= ground && underground >= cave && underground > 0)
            return VoxelType.Underground;
        if (cave > 0)
            return VoxelType.Cave;

        // fallback
        return VoxelType.Ground;
    }

    /// <summary>
    /// Maps VoxelType to submesh index:
    /// 0 = Ground, 1 = Underground, 2 = Cave.
    /// </summary>
    private static int MaterialToSubmeshIndex(VoxelType type)
    {
        switch (type)
        {
            case VoxelType.Ground: return 0;
            case VoxelType.Underground: return 1;
            case VoxelType.Cave: return 2;
            default: return 0;
        }
    }

    /// <summary>
    /// Adds a vertex to global lists and returns its index.
    /// 현재는 중복 정점 캐싱 안 하고, 간단히 계속 추가하는 구조.
    /// 필요하면 나중에 vertex weld / 캐시 추가로 더 최적화 가능.
    /// </summary>
    private static int AddVertex(
        List<Vector3> vertices,
        List<Vector3> normals,
        List<Vector2> uvs,
        Vector3 position,
        float voxelSize)
    {
        int index = vertices.Count;
        vertices.Add(position);
        normals.Add(Vector3.zero); // 나중에 RecalculateNormals로 덮어씀
        // 간단한 planar UV
        uvs.Add(new Vector2(position.x / voxelSize, position.z / voxelSize));
        return index;
    }
