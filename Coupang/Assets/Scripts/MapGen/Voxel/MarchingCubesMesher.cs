    /// <summary>
    /// Builds a smooth marching-cubes mesh from voxel data.
    /// </summary>
    /// <param name="voxels">VoxelType 3D array [x,y,z].</param>
    /// <param name="voxelSize">Size of one voxel edge in world units.</param>
    /// <param name="isoLevel">
    /// Iso-surface threshold in [0,1]. 
    /// For binary solid/air 필드인 경우 0.5 추천.
    /// </param>
    public static Mesh BuildMesh(VoxelType[,,] voxels, float voxelSize, float isoLevel = 0.5f)
    {
        if (voxels == null)
        {
            Debug.LogError("MarchingCubesMesher.BuildMesh: voxels is null.");
            return new Mesh();
        }

        int sizeX = voxels.GetLength(0);
        int sizeY = voxels.GetLength(1);
        int sizeZ = voxels.GetLength(2);

        if (sizeX <= 1 || sizeY <= 1 || sizeZ <= 1)
        {
            Debug.LogWarning("MarchingCubesMesher.BuildMesh: voxel grid too small.");
            return new Mesh();
        }

        // ----------------------------------------------------------------
        // 1) Build scalar field (density) and corner material map
        // ----------------------------------------------------------------
        int gx = sizeX + 1;
        int gy = sizeY + 1;
        int gz = sizeZ + 1;

        float[,,] density = new float[gx, gy, gz];
        VoxelType[,,] cornerMat = new VoxelType[gx, gy, gz];

        BuildScalarField(voxels, density, cornerMat);

        // ----------------------------------------------------------------
        // 2) March over all cubes
        // ----------------------------------------------------------------
        List<Vector3> vertices = new List<Vector3>();
        List<Vector3> normals = new List<Vector3>();
        List<Vector2> uvs = new List<Vector2>();

        List<int> triGround = new List<int>(); // submesh 0
        List<int> triUnderground = new List<int>(); // submesh 1
        List<int> triCave = new List<int>(); // submesh 2

        // Temporary arrays reused per cube
        float[] cubeValues = new float[8];
        VoxelType[] cubeCornerTypes = new VoxelType[8];
        Vector3[] cubeCornerPos = new Vector3[8];
        Vector3[] edgeVertex = new Vector3[12];
        int[] edgeVertIndex = new int[12];

        for (int x = 0; x < sizeX; x++)
        {
            for (int y = 0; y < sizeY; y++)
            {
                for (int z = 0; z < sizeZ; z++)
                {
                    // Fill cube corner data
                    for (int i = 0; i < 8; i++)
                    {
                        int cx = x + (int)CornerOffsets[i].x;
                        int cy = y + (int)CornerOffsets[i].y;
                        int cz = z + (int)CornerOffsets[i].z;

                        cubeValues[i] = density[cx, cy, cz];
                        cubeCornerTypes[i] = cornerMat[cx, cy, cz];

                        Vector3 cornerLocal = new Vector3(
                            (x + CornerOffsets[i].x) * voxelSize,
                            (y + CornerOffsets[i].y) * voxelSize,
                            (z + CornerOffsets[i].z) * voxelSize
                        );
                        cubeCornerPos[i] = cornerLocal;
                    }

                    // Compute cube index (which corners are "inside")
                    int cubeIndex = 0;
                    for (int i = 0; i < 8; i++)
                    {
                        if (cubeValues[i] > isoLevel)
                        {
                            cubeIndex |= 1 << i;
                        }
                    }

                    // No intersection for this configuration
                    int edgeMask = edgeTable[cubeIndex];
                    if (edgeMask == 0)
                        continue;

                    // Interpolate intersection vertex on each active edge
                    for (int e = 0; e < 12; e++)
                    {
                        if ((edgeMask & (1 << e)) == 0)
                            continue;

                        int c0 = EdgeCorners[e, 0];
                        int c1 = EdgeCorners[e, 1];

                        float v0 = cubeValues[c0];
                        float v1 = cubeValues[c1];

                        Vector3 p0 = cubeCornerPos[c0];
                        Vector3 p1 = cubeCornerPos[c1];

                        float t = 0.5f;
                        float denom = (v1 - v0);
                        if (Mathf.Abs(denom) > 1e-6f)
                        {
                            t = (isoLevel - v0) / denom;
                        }

                        edgeVertex[e] = Vector3.Lerp(p0, p1, t);
                    }

                    // Decide which material this cube's triangles should use
                    VoxelType triMatType = PickDominantMaterial(cubeCornerTypes);
                    int submeshIndex = MaterialToSubmeshIndex(triMatType);

                    List<int> targetList = triGround;
                    switch (submeshIndex)
                    {
                        case 0: targetList = triGround; break;
                        case 1: targetList = triUnderground; break;
                        case 2: targetList = triCave; break;
                    }

                    // For each triangle described by triTable[cubeIndex], add its vertices.
                    for (int i = 0; i < 16; i += 3)
                    {
                        int e0 = triTable[cubeIndex, i];
                        if (e0 == -1)
                            break;

                        int e1 = triTable[cubeIndex, i + 1];
                        int e2 = triTable[cubeIndex, i + 2];

                        int vIndex0 = AddVertex(vertices, normals, uvs, edgeVertex[e0], voxelSize);
                        int vIndex1 = AddVertex(vertices, normals, uvs, edgeVertex[e1], voxelSize);
                        int vIndex2 = AddVertex(vertices, normals, uvs, edgeVertex[e2], voxelSize);

                        targetList.Add(vIndex0);
                        targetList.Add(vIndex1);
                        targetList.Add(vIndex2);
                    }
                }
            }
        }

        // ----------------------------------------------------------------
        // 3) Build Unity mesh
        // ----------------------------------------------------------------
        Mesh mesh = new Mesh();
        mesh.indexFormat = vertices.Count > 65000
            ? IndexFormat.UInt32
            : IndexFormat.UInt16;

        mesh.SetVertices(vertices);
        // Normals will be recalculated globally for smooth shading
        mesh.RecalculateNormals();
        mesh.SetUVs(0, uvs);

        mesh.subMeshCount = 3;
        mesh.SetTriangles(triGround, 0, true);
        mesh.SetTriangles(triUnderground, 1, true);
        mesh.SetTriangles(triCave, 2, true);

        mesh.RecalculateBounds();
        return mesh;
    }

